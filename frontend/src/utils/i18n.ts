export type TranslationKey = keyof (typeof messages)['it']

function loadLocale(): AppLocale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'it' || stored === 'en') return stored
  } catch {
    /* Keep the Italian default. */
  }
  return 'it'
}
export function setLocale(value: AppLocale) {
  locale.value = value
  document.documentElement.lang = value
  try {
    localStorage.setItem(STORAGE_KEY, value)
  } catch {
    /* Keep it in memory. */
  }
}
export function getLocale(): AppLocale {
  return locale.value
}
export function localeTag(): string {
  return locale.value === 'en' ? 'en-GB' : 'it-IT'
}
export function translate(key: TranslationKey, params: TranslationParams = {}): string {
  let message: string = messages[locale.value][key]
  for (const [name, value] of Object.entries(params))
    message = message.replaceAll(`{${name}}`, String(value))
  return message
}
export function useI18n() {
  return { locale, localeTag: computed(localeTag), setLocale, t: translate }
}
document.documentElement.lang = locale.value
